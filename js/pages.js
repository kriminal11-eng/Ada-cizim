const f = (n) => +n.toFixed(1);
const c = (cx, cy, r, a = '') => `<circle cx="${cx}" cy="${cy}" r="${r}" ${a}/>`;
const e = (cx, cy, rx, ry, a = '') => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" ${a}/>`;
const r = (x, y, w, h, rr = 0, a = '') => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rr}" ${a}/>`;
const p = (d, a = '') => `<path d="${d}" ${a}/>`;
const l = (d) => `<path d="${d}" fill="none"/>`;
const dot = (cx, cy, rr) => c(cx, cy, rr, 'fill="#222"');
const eye = (cx, cy, rr = 6) =>
  c(cx, cy, rr, 'fill="#222"') + c(f(cx + rr * 0.35), f(cy - rr * 0.35), f(rr * 0.38), 'fill="#fff" stroke="none"');
const mirror = (inner) => `<g transform="matrix(-1 0 0 1 400 0)">${inner}</g>`;

function star(cx, cy, R, rot = -90) {
  let d = '';
  for (let i = 0; i < 10; i++) {
    const rr = i % 2 ? R * 0.45 : R;
    const a = ((rot + i * 36) * Math.PI) / 180;
    d += (i ? 'L' : 'M') + f(cx + rr * Math.cos(a)) + ' ' + f(cy + rr * Math.sin(a));
  }
  return p(d + 'Z');
}

function heart(cx, cy, s) {
  return p(
    `M${cx} ${f(cy + s * 0.9)} C${f(cx - s * 1.5)} ${cy} ${f(cx - s * 0.9)} ${f(cy - s * 1.1)} ${cx} ${f(cy - s * 0.35)} ` +
      `C${f(cx + s * 0.9)} ${f(cy - s * 1.1)} ${f(cx + s * 1.5)} ${cy} ${cx} ${f(cy + s * 0.9)} Z`
  );
}

function cloud(x, y, s = 1) {
  const k = (n) => f(n * s);
  return p(
    `M${x} ${y} c${k(-20)} 0 ${k(-24)} ${k(-26)} ${k(-2)} ${k(-28)} c${k(2)} ${k(-22)} ${k(34)} ${k(-26)} ${k(40)} ${k(-8)} ` +
      `c${k(10)} ${k(-14)} ${k(34)} ${k(-8)} ${k(32)} ${k(10)} c${k(18)} ${k(2)} ${k(16)} ${k(26)} ${k(-4)} ${k(26)} Z`
  );
}

function sun(cx, cy, R) {
  let o = '';
  for (let i = 0; i < 8; i++) {
    const a = (i * Math.PI) / 4;
    o += l(`M${f(cx + Math.cos(a) * (R + 6))} ${f(cy + Math.sin(a) * (R + 6))} L${f(cx + Math.cos(a) * (R + 16))} ${f(cy + Math.sin(a) * (R + 16))}`);
  }
  return o + c(cx, cy, R) + dot(f(cx - R * 0.33), f(cy - R * 0.15), 2.5) + dot(f(cx + R * 0.33), f(cy - R * 0.15), 2.5) +
    l(`M${f(cx - R * 0.4)} ${f(cy + R * 0.25)} Q${cx} ${f(cy + R * 0.6)} ${f(cx + R * 0.4)} ${f(cy + R * 0.25)}`);
}

function flower(x, y, s = 1) {
  let o = l(`M${x} ${y} L${x} ${f(y + 40 * s)}`);
  o += p(`M${x} ${f(y + 30 * s)} C${f(x + 6 * s)} ${f(y + 18 * s)} ${f(x + 18 * s)} ${f(y + 18 * s)} ${f(x + 20 * s)} ${f(y + 20 * s)} C${f(x + 16 * s)} ${f(y + 30 * s)} ${f(x + 8 * s)} ${f(y + 32 * s)} ${x} ${f(y + 30 * s)} Z`);
  for (let k = 0; k < 5; k++) {
    const a = -Math.PI / 2 + (k * 2 * Math.PI) / 5;
    o += c(f(x + 11 * s * Math.cos(a)), f(y + 11 * s * Math.sin(a)), f(8 * s));
  }
  return o + c(x, y, f(6.5 * s));
}

function scallop(cx, cy, R, n, b) {
  let d = '';
  for (let i = 0; i < n; i++) {
    const a0 = (i / n) * 2 * Math.PI, a1 = ((i + 1) / n) * 2 * Math.PI, am = (a0 + a1) / 2;
    if (i === 0) d += `M${f(cx + R * Math.cos(a0))} ${f(cy + R * Math.sin(a0))}`;
    d += ` Q${f(cx + (R + b * 2) * Math.cos(am))} ${f(cy + (R + b * 2) * Math.sin(am))} ${f(cx + R * Math.cos(a1))} ${f(cy + R * Math.sin(a1))}`;
  }
  return p(d + 'Z');
}

function svg(inner, defs = '') {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300" width="1400" height="1050">${defs ? `<defs>${defs}</defs>` : ''}` +
    `<g fill="#fff" stroke="#222" stroke-width="4" stroke-linejoin="round" stroke-linecap="round">${inner}</g></svg>`;
}

